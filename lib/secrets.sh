# shellcheck shell=bash
# lib/secrets.sh — the den bundle: load, validate, render, purge.
# Contract: docs/den/CONTRACT.md. Bash 3.2.

DEN_SECRETS_STATUS=${DEN_SECRETS_STATUS:-missing}
DEN_SECRETS_FILE=${DEN_SECRETS_FILE:-}
DEN_SECRETS_SOURCE=${DEN_SECRETS_SOURCE:-}
DEN_SECRETS_SOURCE_FILE=${DEN_SECRETS_SOURCE_FILE:-}

den_secrets_set() {
  DEN_SECRETS_STATUS=$1
  DEN_SECRETS_FILE=$2
  DEN_SECRETS_SOURCE=$3
  DEN_SECRETS_SOURCE_FILE=$4
  export DEN_SECRETS_STATUS DEN_SECRETS_FILE DEN_SECRETS_SOURCE DEN_SECRETS_SOURCE_FILE
}

den_secrets_valid() {
  local file=${1:-}
  if [ ! -r "$file" ]; then
    return 1
  fi
  if ! command -v jq >/dev/null 2>&1; then
    return 1
  fi
  jq -e 'type == "object" and .version == 1 and (.env | type == "object") and ([.env[] | type] | all(. == "string"))' \
    "$file" >/dev/null 2>&1
}

den_secrets_recorded_path() {
  local record="$DEN_STATE_DIR/secrets.path" value=""
  if [ -r "$record" ]; then
    value=$(head -n 1 "$record" 2>/dev/null) || value=""
    if [ -n "$value" ] && [ -r "$value" ]; then
      printf '%s' "$value"
    fi
  fi
}

# den_with_timeout SECONDS CMD...: run CMD, killed after SECONDS. macOS has no
# timeout(1); perl is on both macOS and Ubuntu. A 1Password approval nobody
# answers must not hang the run.
den_with_timeout() {
  local secs=$1
  shift
  perl -e 'alarm shift @ARGV; exec @ARGV or exit 127' "$secs" "$@"
}

den_secrets_load() {
  local doc="$DEN_RUNTIME/secrets/den.json"
  local candidate="" recorded="" vault=${OP_VAULT:-Private}
  if [ -z "${DEN_RUNTIME:-}" ]; then
    den_die "secrets: no runtime directory"
  fi
  mkdir -p "$DEN_RUNTIME/secrets"
  den_secrets_set missing "" "" ""
  # No `op whoami` gate: with the 1Password app integration, whoami says "not
  # signed in" and shows no prompt, while `op document get` raises the approval
  # prompt and works (seen 2026-11-19). The timeout covers a prompt nobody answers.
  if command -v op >/dev/null 2>&1; then
    ui_info "secrets: asking 1Password for the den document (approve the prompt)"
    if den_with_timeout "${DEN_OP_TIMEOUT:-60}" op document get den --vault "$vault" >"$doc.tmp" 2>/dev/null; then
      if den_secrets_valid "$doc.tmp"; then
        mv "$doc.tmp" "$doc"
        chmod 600 "$doc"
        den_secrets_set ok "$doc" op ""
        ui_info "secrets: loaded the den document from 1Password"
        return 0
      fi
    fi
    rm -f "$doc.tmp"
    ui_warn "secrets: could not read the 1Password document den in vault $vault (not approved, locked, missing, or invalid)"
  fi
  recorded=$(den_secrets_recorded_path) || recorded=""
  if [ -n "$recorded" ]; then
    candidate=$recorded
  elif [ -r "$HOME/den.json" ]; then
    candidate="$HOME/den.json"
  fi
  if [ -n "$candidate" ]; then
    if ! den_secrets_valid "$candidate"; then
      den_secrets_set invalid "" file "$candidate"
      ui_warn "secrets: $candidate is not a valid den bundle (want version 1 and env of strings); keeping it"
      return 0
    fi
    cp "$candidate" "$doc"
    chmod 600 "$doc"
    den_secrets_set ok "$doc" file "$candidate"
    ui_info "secrets: loaded $candidate"
    return 0
  fi
  den_secrets_set missing "" "" ""
  ui_info "secrets: none found; phases that need secrets will be skipped"
  return 0
}

den_secret() {
  local path=${1:-} file=${DEN_SECRETS_FILE:-}
  if [ -z "$path" ] || [ -z "$file" ] || [ ! -r "$file" ]; then
    return 0
  fi
  jq -r "$path // empty" "$file" 2>/dev/null || true
}

den_render_env() {
  local out=${1:-} file=${DEN_SECRETS_FILE:-} count="" dir tmp key value escaped
  if [ -z "$out" ]; then
    den_fail "den_render_env needs an output path" "fix the phase that calls it"
  fi
  if [ -z "$file" ] || [ ! -r "$file" ]; then
    den_skip "no secrets bundle loaded" "sign in with \`op signin\`, or drop den.json at ~/den.json"
  fi
  den_secrets_valid "$file" || den_skip "the secrets bundle is invalid" "fix ~/den.json, then run den fix"
  count=$(jq -r '.env | length' "$file" 2>/dev/null) || count=0
  if [ "${count:-0}" -eq 0 ]; then
    den_skip "the secrets bundle has no env keys" "add env keys to the den document or ~/den.json"
  fi
  dir=$(dirname "$out")
  mkdir -p "$dir"
  umask 077
  tmp="$out.tmp.$$.den"
  : >"$tmp"
  chmod 600 "$tmp"
  {
    printf '# generated by den from the secrets bundle; do not edit\n'
    jq -r '.env | to_entries[] | "\(.key)\t\(.value)"' "$file" |
      while IFS=$'\t' read -r key value; do
        case $key in
          ''|*[!A-Za-z0-9_]*)
            ui_warn "secrets: skipping env key with an invalid name: $key"
            continue
            ;;
        esac
        escaped=$(printf '%s' "$value" | sed "s/'/'\\\\''/g")
        printf "export %s='%s'\n" "$key" "$escaped"
      done
  } >"$tmp"
  if command -v zsh >/dev/null 2>&1 && ! zsh -n "$tmp" 2>/dev/null; then
    rm -f "$tmp"
    den_fail "the generated env file failed zsh -n" "report this as a den bug"
  fi
  if [ -f "$out" ]; then
    cp -p "$out" "$out.bak"
  fi
  chmod 600 "$tmp"
  mv "$tmp" "$out"
  chmod 600 "$out"
  ui_ok "wrote $count keys to $out"
  den_secrets_purge_source
}

den_secrets_purge_source() {
  local file=${DEN_SECRETS_SOURCE_FILE:-} marker=""
  if [ -z "$file" ] || [ "${DEN_SECRETS_SOURCE:-}" != file ]; then
    return 0
  fi
  if [ -n "${DEN_RUNTIME:-}" ]; then
    marker="$DEN_RUNTIME/secrets/purged"
    if [ -f "$marker" ]; then
      return 0
    fi
  fi
  if [ -f "$file" ]; then
    rm -f "$file"
    if [ -n "$marker" ]; then
      : >"$marker"
    fi
    ui_info "removed $file, as asked; the keys are in ~/.config/zsh/.api-keys.zsh. If the den document is not in 1Password, save it there before the next Mac"
  fi
}
